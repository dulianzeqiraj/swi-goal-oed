def sig_table(doc, rows):
    t = head_repeat(table(doc, ['Role', 'Name and position', 'Signature', 'Date'], [[r, '[name, position]', '', '']
                                                                                    for r in rows], [5.2, 5.6, 3.6, 2.6],
                          size=9.5))
    for r_ in t.rows[1:]:
        r_.height = Cm(1.1)
    ph_cells(t)
    return t


def main(out):
    doc = Document()
    s = doc.sections[0]
    s.page_width, s.page_height = Cm(21.0), Cm(29.7)
    s.left_margin = s.right_margin = Cm(2.2); s.top_margin = s.bottom_margin = Cm(1.8)
    st = doc.styles['Normal']; st.font.name = 'Arial'; st.font.size = Pt(10.5)

    # cover: how to use
    p = para(doc, 2); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    put(p, '**CERTAIN-COAST — Intellectual Property Rights Agreement (draft)**', size=16, color='1F3864')
    p = para(doc, 8); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    put(p, 'How to use this draft (remove this page before signing)', size=11, color='52606D', italic=True)
    for h in HOW:
        q = para(doc, 4, 0.3); put(q, '• ' + h)
    p = para(doc, 4, before=4); put(p, 'Sources: ', size=9.5, color='52606D', italic=True)
    link(p, TEMPLATE, 'NATO SPS MYP Sample IPR Agreement', size=9.5); put(p, '; ', size=9.5, color='52606D')
    link(p, HANDBOOK, 'SPS MYP Handbook (version of April 2026), Section "Project Plan"', size=9.5)
    put(p, '. The Handbook: an IPR agreement among the participants, their institutions and end-users (if applicable), "or '
           'a waiver, agreed by all participants and their institutions, stating that an IPR agreement is not necessary; '
           'NATO makes no claim to intellectual property developed under MYP grants."', size=9.5, color='52606D',
        italic=True)
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    # agreement
    p = para(doc, 6); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    put(p, '**INTELLECTUAL PROPERTY RIGHTS AGREEMENT**', size=14, color='1F3864')
    for a, b in [('PROJECT:', f'CERTAIN-COAST — {FULL}'), ('SPS PROJECT NUMBER:', '[assigned by the SPS Programme]')]:
        q = para(doc, 2); put(q, f'**{a}** {b}')
    q = para(doc, 6, before=4); put(q, 'THIS AGREEMENT is made the [day] day of [month, year]')
    put(para(doc, 3), '**BETWEEN**')
    parties = [('A', '[NPD institution: full name, postal address, Albania]', '[short name A]'),
               ('B', '[PPD institution: full name, postal address, partner country]', '[short name B]'),
               ('C', '[institution of any additional Co-Director: full name, postal address, country]', '[short name C]')]
    for code, txt, short in parties:
        q = para(doc, 2, 0.4); put(q, f'{code}  "{txt}", hereinafter called "{short}",')
    q = para(doc, 6, before=3)
    put(q, 'and collectively to be called the "Parties" for the purpose of the Agreement only. Any statutory or other '
           'implication from the use of the term "Party" is hereby expressly excluded. The end-users named in Annex 1 sign '
           'this Agreement to accept Articles 1.2.4, 2.3, 5.4 and 9.5; they are not Parties for the other Articles.')
    put(para(doc, 3), '**WHEREAS**')
    whereas = [
        'The Parties have expertise in the field of coastal groundwater and seawater intrusion, coastal geodesy, '
        'geotechnics and statistics for early warning, and wish to undertake joint research and exploitation of results in '
        'this field.',
        'This project will benefit from financial support through the NATO Science for Peace and Security (SPS) Programme.',
        'NATO wishes the results of the research undertaken to be applied to the benefit of the Parties, and waives any claim '
        'to ownership of Intellectual Property Rights deriving from such research as well as any income resulting from the '
        'exploitation of said Intellectual Property Rights.',
        '(added) The end-users named in Annex 1 provide site access, data and staff time, receive no SPS funds, and keep the '
        'ownership of the data they provide.',
    ]
    for i, w in enumerate(whereas, start=1):
        q = para(doc, 3, 0.4); put(q, f'({i}) {w}')
    put(para(doc, 4, before=4), '**IT IS AGREED as follows:**')
    for kind, txt in ARTICLES:
        if kind == 'h':
            q = para(doc, 3, before=6); q.paragraph_format.keep_with_next = True; put(q, f'**{txt}**', color='1F3864')
        elif kind == 'h2':
            q = para(doc, 2, before=2); q.paragraph_format.keep_with_next = True; put(q, f'**{txt}**')
        else:
            q = para(doc, 3); q.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY; put(q, txt)

    q = para(doc, 4, before=8); q.paragraph_format.keep_with_next = True
    put(q, 'Signatures (with date) of the NPD, the PPD and all other project co-directors as well as the head of their '
           'institutions (or the person responsible for IPR matters) and the end-user(s) involved in the project.')
    sig_table(doc, ['NPD', 'Head of the NPD\'s institution', 'PPD', 'Head of the PPD\'s institution',
                    '[Other Co-Director]', '[Head of that institution]'] +
              [f'End-user {i} (Director): {e}' for i, e in enumerate(END_USERS, start=1)])

    # annexes
    heading(doc, 'Annex 1. Parties and end-users', 12)
    t = head_repeat(table(doc, ['', 'Name', 'Country', 'Role in CERTAIN-COAST', 'Representative'],
                          [['A', '[NPD institution]', 'Albania', 'NPD; WP1–WP5, WP7', '[name]'],
                           ['B', '[PPD institution]', '[country]', 'PPD; WP6, transfer study', '[name]'],
                           ['C', '[institution]', '[country]', '[role]', '[name]']] +
                          [[f'E{i}', e, '[country]', 'End-user (no SPS funds)', '[name]']
                           for i, e in enumerate(END_USERS, start=1)],
                          [1.0, 5.0, 2.4, 5.0, 3.2], size=9))
    ph_cells(t)
    heading(doc, 'Annex 2. Background Intellectual Property', 12)
    t = head_repeat(table(doc, ['Party', 'Background Intellectual Property', 'Conditions'],
                          [['A', 'Preparatory software and test beds of 2026 (the reviews with tests) and the calibrated '
                                 'chloride model of the Fushë-Kuqe aquifer [confirm ownership and list]',
                            'Free for the project (1.2.2); [licence for exploitation: open, or on fair and reasonable '
                            'terms]'],
                           ['B', '[list, or "none"]', '[conditions]'],
                           ['C', '[list, or "none"]', '[conditions]']],
                          [1.4, 9.0, 6.2], size=9))
    ph_cells(t)

    # alternative: waiver statement
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
    p = para(doc, 6); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    put(p, '**Alternative: statement that an IPR agreement is not necessary**', size=13, color='1F3864')
    q = para(doc, 6); put(q, 'Use this page instead of the agreement only if all institutions agree. Project: CERTAIN-COAST '
                             f'— {FULL}. SPS project number: [assigned by the SPS Programme].', size=10, color='52606D',
                          italic=True)
    waiver = [
        'The undersigned Co-Directors of CERTAIN-COAST and the representatives of their institutions state that an '
        'Intellectual Property Rights agreement among them is not necessary for this project, for the following reasons:',
        '1. All software, documentation and derived data products of the project that contain no restricted information '
        'will be released openly, the software under the [Apache License 2.0] and the data products under [CC BY 4.0], each '
        'with a DOI (deliverable D6.1).',
        '2. No participant intends to file patents or other registered rights on the results of the project.',
        '3. The data provided by the end-users remain their property and are governed by the data access agreements '
        'concluded with each of them (task T7.2); restricted information about the critical assets is never published.',
        '4. Should any participant later wish to protect a result, the participants will first conclude an IPR agreement '
        'based on the NATO SPS MYP Sample IPR Agreement and inform the SPS Programme Office.',
        'We note that NATO makes no claim to intellectual property developed under MYP grants.',
    ]
    for w in waiver:
        q = para(doc, 4); q.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY; put(q, w)
    sig_table(doc, ['NPD', 'Head of the NPD\'s institution', 'PPD', 'Head of the PPD\'s institution',
                    '[Other Co-Director]', '[Head of that institution]'])
    doc.save(out)
    print('saved', out, '| articles', sum(1 for k, _ in ARTICLES if k == 'h'), '| end-users', len(END_USERS))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'CERTAIN-COAST_IPR_Agreement_Draft.docx')
