RES = os.path.join(HERE, 'res')
INK, INK2, GRID = '#0b0b0b', '#52514e', '#d9d8d4'
BLUE, ORANGE, AQUA, YELLOW, MAGENTA, VIOLET = '#2a78d6', '#eb6834', '#1baf7a', '#eda100', '#e87ba4', '#7c5cc4'


def style(ax):
    ax.tick_params(colors=INK2, labelsize=7.5)
    for s_ in ax.spines.values():
        s_.set_color(GRID)


def fig_map(m, Z, S):
    b = m.base
    post = np.load(os.path.join(ROOT, 'chloride_fk', 'results', 'post_ensemble.npz'))
    p250 = (post['Cl_sh'] > M.CL_LIMIT).mean(0)
    fig, ax = plt.subplots(figsize=(6.6, 7.6))
    grid = np.full((b.ny, b.nx), np.nan); grid[m.aj, m.ai] = np.where(m.valid, p250, np.nan)
    out = np.full((b.ny, b.nx), np.nan); out[m.aj, m.ai] = np.where(m.valid, np.nan, 1.0)
    ext = [b.xs[0] - b.dx / 2, b.xs[-1] + b.dx / 2, b.ys[0] - b.dx / 2, b.ys[-1] + b.dx / 2]
    ax.imshow(out, origin='lower', extent=ext, cmap=matplotlib.colors.ListedColormap(['#e6e6e6']), vmin=0, vmax=1, interpolation='nearest')
    im = ax.imshow(grid, origin='lower', extent=ext, cmap='Blues', vmin=0, vmax=1, interpolation='nearest')
    ax.plot(np.r_[b.Bk[:, 0], b.Bk[0, 0]], np.r_[b.Bk[:, 1], b.Bk[0, 1]], color=INK, lw=0.7)
    pl = pd.read_csv(os.path.join(ROOT, 'chloride_fk', 'derived', 'shoreline_polyline.csv'))
    ax.plot(pl['x_km'], pl['y_km'], color=BLUE, lw=0.9, ls='--')
    sc = m.sea_idx
    ax.scatter(m.cx[sc] - b.dx / 2, m.cy[sc], s=6, color=ORANGE, zorder=4, lw=0)
    ax.axhline(M.Y_CUT, color=INK2, lw=0.8, ls=':')
    ax.text(12.2, M.Y_CUT + 0.35, 'southern cut y = 24 km\n(no flow)', fontsize=6.8, color=INK2)
    ids = np.array([str(x) for x in b.wellID])
    def xy(n):
        i = int(np.flatnonzero(ids == n)[0]); return b.Wk[i, 0], b.Wk[i, 1]
    mon = [str(x) for x in Z['mon_ids']]
    best_cl = S['C']['greedy_cl_sh'][0]['well']
    for n in mon:
        x, y = xy(n)
        hi = n == best_cl
        ax.scatter(x, y, s=34 if hi else 16, marker='o', facecolor=AQUA if hi else 'white', edgecolor=INK, lw=0.6, zorder=5)
        if hi or n in ('A3', 'A10', 'A23'):
            ax.annotate(n, (x, y), xytext=(4, 3), textcoords='offset points', fontsize=6.8, color=INK)
    for n in S['supply']:
        x, y = xy(n)
        ax.scatter(x, y, s=70, marker='v', facecolor=YELLOW, edgecolor=INK, lw=0.7, zorder=6)
        ax.annotate(n, (x, y), xytext=(-20, -2) if n == 'A1' else (5, -9), textcoords='offset points', fontsize=7, color=INK, fontweight='bold')
    D = S['B']['designs']
    for dn, mk, fc in (('fk_prag_mar', 'D', 'white'), ('swap_chem', 's', MAGENTA)):
        for st in D[dn]['sites']:
            ax.scatter(st['x'], st['y'], s=52, marker=mk, facecolor=fc, edgecolor=INK, lw=0.8, zorder=7)
    ax.set_xlim(-1.5, 17.5); ax.set_ylim(23, 53)
    ax.set_aspect('equal')
    ax.set_xlabel('easting from $x_0$ (km)', color=INK2, fontsize=8.5); ax.set_ylabel('northing from $y_0$ (km)', color=INK2, fontsize=8.5)
    style(ax)
    cb = fig.colorbar(im, ax=ax, fraction=0.035, pad=0.02)
    cb.set_label('posterior P(shallow Cl > 250 mg/L), no pumping', fontsize=7.5, color=INK2); cb.ax.tick_params(labelsize=7)
    h = [Line2D([], [], color=ORANGE, marker='o', ls='', ms=4, label='sea contact: Robin link to the shoreline (92 cells)'),
         Line2D([], [], color=BLUE, ls='--', lw=0.9, label='GLOBE shoreline'),
         Line2D([], [], color=INK, lw=0.7, label='aquifer polygon: no-flow margin'),
         Patch(facecolor='#e6e6e6', edgecolor='none', label='outside the model sector'),
         Line2D([], [], marker='v', color='w', markerfacecolor=YELLOW, markeredgecolor=INK, ms=8, label='supply wells (pumped)'),
         Line2D([], [], marker='o', color='w', markerfacecolor='white', markeredgecolor=INK, ms=5, label='candidate monitoring wells'),
         Line2D([], [], marker='o', color='w', markerfacecolor=AQUA, markeredgecolor=INK, ms=6, label=f'best chloride sample ({best_cl}, shallow)'),
         Line2D([], [], marker='D', color='w', markerfacecolor='white', markeredgecolor=INK, ms=6, label='recharge sites, head proxy (PRAG-MAR)'),
         Line2D([], [], marker='s', color='w', markerfacecolor=MAGENTA, markeredgecolor=INK, ms=6, label='recharge sites, chemistry (PUSI-GO)')]
    ax.legend(handles=h, loc='upper center', bbox_to_anchor=(0.55, -0.08), ncol=2, fontsize=6.4, frameon=False)
    fig.savefig(os.path.join(RES, 'figP1_map.png'), dpi=220, bbox_inches='tight')
    plt.close(fig)


def fig_results(m, Z, S, X):
    import pusi_analysis as PA
    fig = plt.figure(figsize=(12.6, 8.4))
    gs = fig.add_gridspec(2, 3, hspace=0.48, wspace=0.34)
    # (a) chemistry threshold vs potential at A1 under pumping
    a = fig.add_subplot(gs[0, 0])
    QA, QB = S['pumping_m3_d']
    tC = PA.tau_chem(); phS = PA.phi_sup(QA, QB)
    V = PA.V; wV = PA.wV
    rng = np.random.default_rng(3); ii = V[rng.choice(len(V), 2500, p=wV)]
    hS, _ = PA.state(phS, PA.dS, PA.BS)
    hcal = S['h_cal_m'][0]
    fC = phS[ii, 0] < tC[ii, 0]; fK = hS[ii, 0] < hcal
    cols = np.where(fC & fK, INK2, np.where(fC, ORANGE, np.where(fK, BLUE, '#bdbdbd')))
    a.scatter(tC[ii, 0], phS[ii, 0], s=4, c=cols, lw=0, alpha=0.7)
    lim = [10, 1500]
    a.plot(lim, lim, color=INK, lw=1.0)
    a.set_xscale('log'); a.set_yscale('log'); a.set_xlim(lim); a.set_ylim(lim)
    a.set_xlabel(r'chemistry threshold $\phi^*_{A1}$ (m$^2$): shallow Cl = 250 mg/L', color=INK2, fontsize=8)
    a.set_ylabel(r'potential at A1 under pumping $\phi_{A1}$ (m$^2$)', color=INK2, fontsize=8)
    h = [Line2D([], [], marker='o', ls='', color=INK2, ms=4, label='fails both'), Line2D([], [], marker='o', ls='', color=ORANGE, ms=4, label='fails chemistry only'),
         Line2D([], [], marker='o', ls='', color=BLUE, ms=4, label=f'fails tuned head ({hcal:.2f} m) only'), Line2D([], [], marker='o', ls='', color='#bdbdbd', ms=4, label='fails neither'),
         Line2D([], [], color=INK, lw=1, label=r'$\phi=\phi^*$ (chemistry boundary)')]
    a.legend(handles=h, fontsize=6.3, loc='upper left', frameon=True, framealpha=0.9, edgecolor=GRID)
    a.set_title('(a) The threshold is random; heads do not see it', fontsize=9, loc='left', color=INK)
    style(a)
    # (b) recharge designs
    bx = fig.add_subplot(gs[0, 1])
    D = S['B']['designs']
    rows = [('none', 'no recharge'), ('fk_prag_mar', 'head proxy\n(PRAG-MAR sites)'), ('swap_chem', 'chemistry\n(PUSI-GO sites)')]
    x = np.arange(len(rows))
    bx.bar(x - 0.18, [D[k]['P_chem'] for k, _ in rows], width=0.34, color=MAGENTA, label='chloride standard (250 mg/L)')
    bx.bar(x + 0.18, [D[k]['P_proxy'] for k, _ in rows], width=0.34, color=BLUE, label='head proxy (h < 1 m)')
    for xi, (k, _) in zip(x, rows):
        bx.text(xi - 0.18, D[k]['P_chem'] + 0.01, f"{D[k]['P_chem']:.3f}", ha='center', fontsize=6.8, color=INK)
        bx.text(xi + 0.18, D[k]['P_proxy'] + 0.01, f"{D[k]['P_proxy']:.3f}", ha='center', fontsize=6.8, color=INK)
    bx.set_xticks(x); bx.set_xticklabels([l for _, l in rows], fontsize=7.2)
    bx.set_ylabel('P(A1 or P10 fails), evaluation half', color=INK2, fontsize=8)
    bx.legend(fontsize=6.6, frameon=False, loc='upper right')
    bx.set_ylim(0, 0.72)
    bx.set_title('(b) Three recharge wells of 5,000 m$^3$/d', fontsize=9, loc='left', color=INK)
    bx.grid(axis='y', color=GRID, lw=0.6); style(bx)
    # (c) monitoring information
    c = fig.add_subplot(gs[0, 2])
    C = S['C']
    labs = [('PRAG-GO\n3 heads', C['prag_go_heads_A3_A10_A23']), ('best\n3 heads', C['greedy_heads'][-1]['eig']),
            (f"1 Cl\n({C['greedy_cl_sh'][0]['well']})", C['greedy_cl_sh'][0]['eig']), ('best\n3 Cl', C['greedy_cl_sh'][-1]['eig']),
            ('best 2\nany type', C['greedy_all'][1]['eig'])]
    cc = [BLUE, BLUE, AQUA, AQUA, VIOLET]
    c.bar(range(len(labs)), [v for _, v in labs], color=cc, width=0.62)
    c.axhline(C['H_prior'], color=INK2, lw=0.9, ls='--')
    c.text(len(labs) - 0.6, C['H_prior'] + 0.012, 'entropy of the event', fontsize=6.6, color=INK2, ha='right')
    for i, (_, v) in enumerate(labs):
        c.text(i, v + 0.012, f'{v:.2f}', ha='center', fontsize=6.8, color=INK)
    c.set_xticks(range(len(labs))); c.set_xticklabels([l for l, _ in labs], fontsize=6.6)
    c.set_ylabel('expected information on the event (nats)', color=INK2, fontsize=8); c.set_ylim(0, 0.78)
    c.set_title('(c) What to measure: chloride, not heads', fontsize=9, loc='left', color=INK)
    c.grid(axis='y', color=GRID, lw=0.6); style(c)
    # (d) safe yield
    d = fig.add_subplot(gs[1, 0])
    Y = C['safe_yield']
    labs = [('none', 'no\ndata'), ('prag_go_heads', 'PRAG-GO\n3 heads'), ('best_3_heads', 'best\n3 heads'), ('best_1_cl', '1 Cl\n(A30)'), ('best_3_cl_sh', 'best\n3 Cl'), ('best_2_all', 'best 2\nany type')]
    d.bar(range(len(labs)), [Y[k]['yield_m3_d'] for k, _ in labs], color=[INK2, BLUE, BLUE, AQUA, AQUA, VIOLET], width=0.62)
    for i, (k, _) in enumerate(labs):
        d.text(i, Y[k]['yield_m3_d'] + 120, f"{Y[k]['yield_m3_d']:,.0f}\n({100 * Y[k]['fail_rate']:.0f}%)", ha='center', fontsize=6.4, color=INK)
    d.set_xticks(range(len(labs))); d.set_xticklabels([l for _, l in labs], fontsize=6.6)
    d.set_ylabel('mean safe pumping, A1 + P10 (m$^3$/d)', color=INK2, fontsize=8)
    d.set_ylim(0, max(Y[k]['yield_m3_d'] for k, _ in labs) * 1.35)
    d.set_title(f"(d) Safe yield bought by data ({C['yield_screen_m']:.0f} m screens, risk ≤ 10%)", fontsize=9, loc='left', color=INK)
    d.grid(axis='y', color=GRID, lw=0.6); style(d)
    # (e)-(f) freshening behind a recharge well
    e = fig.add_subplot(gs[1, 1]); f = fig.add_subplot(gs[1, 2])
    cv = X['curves']; fr = cv['fr']; nc = int(cv['nc']); pv = np.arange(1, len(fr) + 1) / nc
    e.plot(pv, fr[:, G.I_CL], color=MAGENTA, lw=1.5, label='Cl')
    e.plot(pv, fr[:, G.I_NA], color=BLUE, lw=1.5, label='Na')
    e.axhline(250, color=MAGENTA, lw=0.8, ls=':'); e.axhline(200, color=BLUE, lw=0.8, ls=':')
    e.text(7.5, 270, 'Cl limit 250 mg/L', fontsize=6.6, color=MAGENTA); e.text(7.5, 140, 'Na limit 200 mg/L', fontsize=6.6, color=BLUE)
    e.set_yscale('log'); e.set_xlim(0, 10); e.set_ylim(5, 3000)
    e.set_xlabel('pore volumes of recharge water', color=INK2, fontsize=8); e.set_ylabel('outlet concentration (mg/L)', color=INK2, fontsize=8)
    e.legend(fontsize=7, frameon=False, loc='upper right')
    e.set_title('(e) Freshening: chloride governs the standard', fontsize=9, loc='left', color=INK)
    e.grid(color=GRID, lw=0.5); style(e)
    hard = 2 * fr[:, G.I_CA] / G.MW[G.I_CA] + 2 * fr[:, G.I_MG] / G.MW[G.I_MG]
    f.plot(pv, hard, color=VIOLET, lw=1.6)
    f.text(4.2, 2.2, 'E = 60 meq/L,\nsea fraction 5%', fontsize=6.6, color=VIOLET)
    hf = 2 * G.FRESH[G.I_CA] + 2 * G.FRESH[G.I_MG]
    f.axhline(hf, color=INK2, lw=0.8, ls='--'); f.text(6.0, hf + 0.12, 'recharge water (well 193)', fontsize=6.6, color=INK2)
    f.axhline(0, color=INK2, lw=0.6)
    runs = sorted([r for r in X['json']['runs'] if r['f0'] == 0.05], key=lambda r: r['E'])
    for i, r in enumerate(runs):
        yb = -0.45 * (i + 1)
        col = {30: AQUA, 60: VIOLET, 120: ORANGE}[int(r['E'])]
        f.hlines(yb, r['fr_pv_cl'], r['fr_pv_cl'] + r['tail_pv_soft'], color=col, lw=4)
        f.text(r['fr_pv_cl'] + r['tail_pv_soft'] + 0.15, yb - 0.1, f"E = {r['E']:.0f}: {r['tail_pv_soft']:.1f} PV soft", fontsize=6.4, color=col)
    f.text(0.15, -1.75, 'bars: hardness below half that of the recharge water', fontsize=6.2, color=INK2)
    f.set_xlim(0, 10); f.set_ylim(-1.9, 4.6); f.set_yticks([0, 1, 2, 3, 4])
    f.set_xlabel('pore volumes of recharge water', color=INK2, fontsize=8); f.set_ylabel('hardness Ca + Mg (meq/L)', color=INK2, fontsize=8)
    f.set_title('(f) ...but leaves soft Na-HCO$_3$ water behind', fontsize=9, loc='left', color=INK)
    f.grid(color=GRID, lw=0.5); style(f)
    fig.savefig(os.path.join(RES, 'figP2_pusi.png'), dpi=200, bbox_inches='tight')
    plt.close(fig)


def main():
    sys.path.insert(0, HERE)
    m = M.Model()
    Z = np.load(os.path.join(RES, 'ens.npz'))
    S = json.load(open(os.path.join(RES, 'pusi.json')))
    X = dict(curves=np.load(os.path.join(RES, 'exchange_curves.npz')), json=json.load(open(os.path.join(RES, 'exchange.json'))))
    fig_map(m, Z, S)
    fig_results(m, Z, S, X)
    print('wrote res/figP1_map.png, res/figP2_pusi.png')


if __name__ == '__main__':
    main()
